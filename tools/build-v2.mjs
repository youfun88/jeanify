/* Generate v2/index.html — the white-background review build — from index.html.
 *
 * v2 is the same app, the same scripts and the same content as the live site, with one
 * extra stylesheet (v2/light.css) layered on top. Nothing is copied: <base href="../">
 * makes every relative URL in the page and in data.js resolve against the site root,
 * so there is no second set of images or scripts to keep in sync.
 *
 * The page is derived rather than hand-written so it cannot drift from index.html.
 * Run after editing index.html:  npm run build:v2   (also part of npm run build)
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/* Every substitution must hit exactly once. If index.html changes shape, fail loudly
   here instead of publishing a v2 that silently lost its stylesheet or its <base>. */
function swap(html, from, to, label) {
  if (from instanceof RegExp) {
    const hits = html.match(new RegExp(from.source, "g")) || [];
    if (hits.length !== 1) {
      console.error(`build-v2: expected exactly one "${label}" in index.html, found ${hits.length}.`);
      process.exit(1);
    }
    return html.replace(from, () => to);
  }
  const parts = html.split(from);
  if (parts.length !== 2) {
    console.error(`build-v2: expected exactly one "${label}" in index.html, found ${parts.length - 1}.`);
    process.exit(1);
  }
  return parts.join(to);
}

/* With <base href="../">, a bare href="#/about" resolves to the ROOT page's hash and a
   plain click would leave v2 for the dark site. Most links call go() and never get that
   far; this catches the few that rely on the default action. It runs on document, so
   React's own handlers (attached to #root) have already had their say. */
const HASH_LINK_FIX = `<script>
document.addEventListener("click", function (e) {
  if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
  var a = e.target.closest && e.target.closest('a[href^="#"]');
  if (!a) return;
  e.preventDefault();
  window.location.hash = a.getAttribute("href");
});
</script>`;

let html = await readFile(join(ROOT, "index.html"), "utf8");

html = swap(html, `<base href="/" />`, `<base href="../" />`, "base href");
// The live pages route by real path (/about/); v2 is a single file, so it keeps the
// hash router. This must run before core.compiled.js and the hash-forwarding script.
html = swap(html, `<head>\n`, `<head>\n<script>window.JR_ROUTER = "hash";</script>\n`, "head tag");
// index.html carries the prerendered home page; v2 renders itself (its links are
// #/hash links, which wouldn't match the prerendered /real/ ones).
{
  const re = /<div id="root">[\s\S]*<\/div>\n<!-- \/root -->/;
  if (!re.test(html)) { console.error("build-v2: prerendered root not found in index.html."); process.exit(1); }
  html = html.replace(re, `<div id="root"></div>`);
}
// A review copy must not compete with the real page in search results. The canonical
// link is left pointing at the live site for the same reason.
html = swap(
  html,
  `<meta name="robots" content="index, follow, max-image-preview:large" />`,
  `<meta name="robots" content="noindex, nofollow" />`,
  "robots meta",
);
html = swap(
  html,
  `<meta name="theme-color" content="#0b0d10" />`,
  `<meta name="theme-color" content="#ffffff" />`,
  "theme-color meta",
);
html = swap(
  html,
  /<style id="site-css">[\s\S]*?<\/style>/,
  `<link rel="stylesheet" href="styles.css" />\n<link rel="stylesheet" href="v2/light.css" />`,
  "inlined site CSS",
);
html = swap(html, `</body>`, `${HASH_LINK_FIX}\n</body>`, "closing body tag");
html = swap(
  html,
  `<!-- GENERATED by tools/build-pages.mjs from the .jsx sources — do not hand-edit. -->`,
  `<!-- GENERATED by tools/build-v2.mjs from index.html — do not hand-edit. -->`,
  "generated comment",
);

await mkdir(join(ROOT, "v2"), { recursive: true });
const dest = join(ROOT, "v2", "index.html");
const prev = await readFile(dest, "utf8").catch(() => null);
if (prev === html) {
  console.log("  =  v2/index.html");
} else {
  await writeFile(dest, html, "utf8");
  console.log("  →  index.html  ⇒  v2/index.html");
}
